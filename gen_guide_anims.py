#!/usr/bin/env python3
"""Writes guide-anims.js: the frames the user guide plays, bit-packed + base64, with each frame's hold time.
  1. The design sheet's own frames (<firmware repo>/art/reference/dino-v1) for the sheet's clips.
  2. The firmware's live screens that the sheet does not have (Wi-Fi setup): export_live_frames.cpp is compiled
     against the firmware sources and run; needs a C++ compiler and a firmware checkout that has the Wi-Fi screens.
Run from this repo:
    python3 gen_guide_anims.py /path/to/pixling_dino_firmware
Deterministic: same firmware in, same file out."""
import base64, json, os, shutil, subprocess, sys, tempfile

FW = sys.argv[1]
REF = os.path.join(FW, 'art/reference/dino-v1')
KEYS = ['idle', 'pet', 'overpet', 'rawr', 'shake', 'pickup', 'tilt', 'sleep', 'wake',
        'time', 'clock', 'menu', 'setalarm', 'alarm', 'snooze', 'dismiss',
        'focuspick', 'focus', 'focusdone', 'break', 'stopwatch']
LIVE_KEYS = ['wifi_menu', 'wifi_pair', 'wifi_joined', 'wifi_connecting', 'wifi_done', 'wifi_fail']
W, H = 128, 64
HERE = os.path.dirname(os.path.abspath(__file__))


def pack(px):
    packed = bytearray(W * H // 8)
    for i, v in enumerate(px):
        if v:
            packed[i >> 3] |= 0x80 >> (i & 7)
    return base64.b64encode(bytes(packed)).decode()


timing = json.load(open(os.path.join(REF, 'dino_timing.json')))
bits = open(os.path.join(REF, 'dino_frames.bin'), 'rb').read()
out = {}
for c in timing['clips']:
    if c['key'] not in KEYS:
        continue
    frames = [{'ms': f['ms'], 'note': f.get('note', ''), 'd': pack(bits[f['index'] * W * H:(f['index'] + 1) * W * H])}
              for f in c['frames']]
    out[c['key']] = {'id': c['id'], 'name': c['name'], 'frames': frames}
missing = [k for k in KEYS if k not in out]
assert not missing, missing

# ---- the firmware's own screens (Wi-Fi setup)
cxx = next((c for c in ('c++', 'g++', 'clang++') if shutil.which(c)), None)
assert cxx, 'no C++ compiler found'
src = os.path.join(FW, 'firmware/src')
with tempfile.TemporaryDirectory() as tmp:
    exe = os.path.join(tmp, 'export_live_frames')
    subprocess.run([cxx, '-std=c++17', '-O1', '-I', src, os.path.join(HERE, 'export_live_frames.cpp'),
                    os.path.join(src, 'face/face.cpp'), os.path.join(src, 'scenes/dino_clips.cpp'),
                    os.path.join(src, 'scenes/dino_live.cpp'), '-o', exe], check=True)
    text = subprocess.run([exe], check=True, capture_output=True, text=True).stdout.splitlines()
cur = None
for line in text:
    if line.startswith('CLIP '):
        key, name, n = line[5:].split('|')
        cur = {'id': 'W', 'name': name, 'frames': [], 'n': int(n)}
        out[key] = cur
    elif line.startswith('FRAME '):
        ms, note = line[6:].split('|', 1)
        cur['frames'].append({'ms': int(ms), 'note': note, 'd': None})
    else:
        raw = bytes.fromhex(line)
        assert len(raw) == W * H // 8
        cur['frames'][-1]['d'] = base64.b64encode(raw).decode()
for k in LIVE_KEYS:
    assert k in out and len(out[k]['frames']) == out[k]['n'] and all(f['d'] for f in out[k]['frames']), k
    del out[k]['n']

with open(os.path.join(HERE, 'guide-anims.js'), 'w') as fh:
    fh.write('// Generated by gen_guide_anims.py from <firmware repo>/art/reference/dino-v1 and the firmware live screens. Do not edit.\n')
    fh.write('window.DINO_ANIMS=' + json.dumps(out, separators=(',', ':')) + ';\n')
print(sum(len(v['frames']) for v in out.values()), 'frames', os.path.getsize(os.path.join(HERE, 'guide-anims.js')) // 1024, 'KB')
